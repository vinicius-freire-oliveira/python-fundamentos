# Texto (str)
nome = "Python"

# Número inteiro (int)
idade = 30

# Número decimal (float)
altura = 1.75

# Valor lógico (bool)
estudando = True


print("Nome:", nome)
print("Idade:", idade)
print("Altura:", altura)
print("Estudando Python?", estudando)


print("\nTipos das variáveis:")

print(type(nome))
print(type(idade))
print(type(altura))
print(type(estudando))